#include<stdio.h>

void CheckSpy(int num)
{
    int sum = 0, product = 1, temp = num;

    while(temp > 0)
    {
        int digit = temp % 10;
        sum += digit;
        product *= digit;
        temp /= 10;
    }

    if(sum == product)
        printf("Spy Number\n");
    else
        printf("Not Spy Number\n");
}

////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////
//
// Application : Checks Spy number.
//
////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////

int main()
{
    int num;

    printf("Enter number : ");
    scanf("%d",&num);

    CheckSpy(num);

    return 0;
}
