#include<stdio.h>

void CheckNeon(int num)
{
    int sq = num * num;
    int sum = 0;

    while(sq > 0)
    {
        sum += sq % 10;
        sq /= 10;
    }

    if(sum == num)
        printf("Neon Number\n");
    else
        printf("Not Neon Number\n");
}

////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////
//
// Application : Checks Neon number.
//
////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////

int main()
{
    int num;

    printf("Enter number : ");
    scanf("%d",&num);

    CheckNeon(num);

    return 0;
}
